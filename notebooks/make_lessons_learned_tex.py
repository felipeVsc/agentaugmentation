def table2():
    lines = ["\\begin{table}[t]", "\\centering",
             "\\caption{Airports (108 tasks): mean and best results of each strategy per model. A mean averages the 9 prompts; "
             "A best is the model's best prompt by F1 (Table~\\ref{tab:a-prompts}). Energy per run as defined in "
             "Section~\\ref{sec:eis}; energy per correct answer counts the three runs of every task.}", "\\label{tab:strategies}", "\\small", "\\setlength{\\tabcolsep}{4pt}",
             "\\begin{tabular}{llrrrrrr}", "\\toprule",
             "Model & Strategy & F1 & P & \\fign & Abst. & Wh/run & Wh/correct \\\\", "\\midrule"]
    for i, m in enumerate(MODELS):
        for j, a in enumerate(["A mean", "A best", "B search", "B search + memory"]):
            r = SC[(SC["model name"] == m) & (SC.approach == a)].iloc[0]
            lab = {"A mean": "A mean", "A best": "A best", "B search": "B search", "B search + memory": "B search + memory"}[a]
            name = m if j == 0 else ""
            lines.append(f"{name} & {lab} & {r.f1:.2f} & {r.precision:.2f} & {r.f1_ign:.2f} & {100 * r.abstention:.0f}\\% & "
                         f"{r.EC:.3f} & {r.Wh_per_correct:.2f} \\\\")
        if i < len(MODELS) - 1:
            lines.append("\\addlinespace")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(lines)


